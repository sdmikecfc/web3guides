/**
 * Season 4 arcade — the STEAM-LIBRARY presentation of the game slate.
 *
 * A big FEATURED HERO (the first game, a full-bleed cover banner) over a grid
 * of cover-art tiles, exactly the Steam library feel Mike asked for. The server
 * page (./page.tsx) owns the data: it reads the registry (src/lib/s4/games.ts),
 * maps each game to a serializable card, and hands them here. This component is
 * purely presentational so it can be a client component (hover polish + the
 * missing-art swap need the browser).
 *
 * ART: each card's background is /s4-art/games/<key>/capsule.png. That art is
 * generated by a separate pass and may be ABSENT — so every hero and tile uses
 * the proven hydration-safe missing-art pattern (ref checks complete &&
 * naturalWidth === 0 at mount, plus onError) and falls back to a premium
 * accent gradient with the game name, looking intentional with zero images.
 *
 * Palette: charcoal #07080c base; per-game accents crimson / gold / violet /
 * ice arrive as props (each game carries its own). No themed WORD is hardcoded
 * here — display names come from the registry via props.
 */
"use client";

import Link from "next/link";
import { useState } from "react";

export type LibraryCard = {
  key: string; // stable registry key; routes to /s4/games/<key>
  name: string; // display name from the registry
  blurb: string; // one-liner
  accent: string; // per-game accent hex
  comingSoon: boolean;
};

const INK = "#07080c";

/**
 * Cover art with graceful absence. A premium accent gradient is always the base
 * layer (it shows through until the PNG paints, and stays if the PNG is
 * missing); the cover image sits on top and hides the gradient when it loads.
 * The ref check catches a 404 that resolved before hydration (onError never
 * fires for those), the proven S4 hero pattern.
 */
function Cover({ src, accent }: { src: string; accent: string }) {
  const [missing, setMissing] = useState(false);
  return (
    <>
      <div
        aria-hidden="true"
        style={{
          position: "absolute",
          inset: 0,
          background:
            "radial-gradient(135% 108% at 50% 0%, " +
            accent +
            "40 0%, rgba(7,8,12,0) 52%), linear-gradient(180deg, #12141d 0%, " +
            INK +
            " 72%)",
        }}
      />
      {!missing ? (
        // eslint-disable-next-line @next/next/no-img-element
        <img
          src={src}
          alt=""
          className="s4lib-cover"
          ref={(el) => {
            if (el && el.complete && el.naturalWidth === 0) setMissing(true);
          }}
          onError={() => setMissing(true)}
          style={{
            position: "absolute",
            inset: 0,
            width: "100%",
            height: "100%",
            objectFit: "cover",
            objectPosition: "center",
            display: "block",
          }}
        />
      ) : null}
    </>
  );
}

function accentVars(accent: string): React.CSSProperties {
  return { "--s4-accent": accent, "--s4-glow": accent + "55" } as React.CSSProperties;
}

