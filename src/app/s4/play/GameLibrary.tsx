/** A Steam-library tile: cover art, bottom scrim, name + one-liner, Play. */
function Tile({ card }: { card: LibraryCard }) {
  const body = (
    <>
      <Cover src={"/s4-art/games/" + card.key + "/capsule.png"} accent={card.accent} />
      {/* accent top hairline for at-a-glance identity */}
      <div
        aria-hidden="true"
        style={{ position: "absolute", top: 0, left: 0, right: 0, height: 3, background: card.accent, opacity: 0.9 }}
      />
      {/* bottom scrim so the name stays legible over any art */}
      <div
        aria-hidden="true"
        style={{
          position: "absolute",
          inset: 0,
          background:
            "linear-gradient(0deg, rgba(4,5,8,0.95) 0%, rgba(4,5,8,0.55) 32%, rgba(4,5,8,0) 62%)",
        }}
      />
      <div
        style={{
          position: "relative",
          zIndex: 1,
          height: "100%",
          display: "flex",
          flexDirection: "column",
          justifyContent: "flex-end",
          padding: 16,
        }}
      >
        <div style={{ fontSize: 18, fontWeight: 800, color: "#fff", lineHeight: 1.12 }}>{card.name}</div>
        <div style={{ fontSize: 12.5, color: "rgba(232,236,245,0.8)", marginTop: 4, lineHeight: 1.4 }}>
          {card.blurb}
        </div>
        {card.comingSoon ? (
          <span
            style={{
              alignSelf: "flex-start",
              marginTop: 12,
              padding: "6px 12px",
              borderRadius: 999,
              border: "1px solid rgba(255,255,255,0.16)",
              background: "rgba(255,255,255,0.05)",
              color: "#aeb6c8",
              fontSize: 11,
              fontWeight: 700,
              letterSpacing: "0.08em",
              textTransform: "uppercase",
            }}
          >
            Coming soon
          </span>
        ) : (
          <span
            className="s4lib-play"
            style={{
              alignSelf: "flex-start",
              marginTop: 12,
              display: "inline-flex",
              alignItems: "center",
              gap: 7,
              padding: "8px 16px",
              borderRadius: 9,
              border: "1px solid " + card.accent + "88",
              background: card.accent + "1f",
              color: "#fff",
              fontSize: 13,
              fontWeight: 800,
              letterSpacing: "0.02em",
            }}
          >
            <span aria-hidden="true">▶</span> Play
          </span>
        )}
      </div>
    </>
  );

  const shellStyle: React.CSSProperties = {
    position: "relative",
    overflow: "hidden",
    display: "block",
    aspectRatio: "3 / 4",
    borderRadius: 14,
    border: "1px solid #1c2236",
    background: INK,
    textDecoration: "none",
    ...accentVars(card.accent),
  };

  if (card.comingSoon) {
    return (
      <div className="s4lib-tile" style={shellStyle}>
        {body}
      </div>
    );
  }
  return (
    <Link className="s4lib-tile" style={shellStyle} href={"/s4/games/" + card.key} aria-label={"Play " + card.name}>
      {body}
    </Link>
  );
}

export function GameLibrary({ cards }: { cards: LibraryCard[] }) {
  if (cards.length === 0) return null;
  // The featured hero spotlights the first game; the grid below still lists
  // every game (the featured one included), the way a Steam library shows the
  // spotlight AND the full shelf.
  const featured = cards[0];
  return (
    <div>
      <style dangerouslySetInnerHTML={{ __html: LIBRARY_CSS }} />
      <Hero card={featured} />
      <div
        style={{
          fontSize: 11,
          letterSpacing: "0.28em",
          color: "#8b95ad",
          textTransform: "uppercase",
          fontWeight: 700,
          margin: "0 0 14px",
        }}
      >
        All games
      </div>
      <div className="s4lib-grid">
        {cards.map((c) => (
          <Tile key={c.key} card={c} />
        ))}
      </div>
    </div>
  );
}

// No backticks or quotes inside this CSS string (server HTML-escaping of a
// <style> text child corrupts quotes and desyncs hydration; the hero uses the
// same dangerouslySetInnerHTML approach for the same reason).
const LIBRARY_CSS =
  ".s4lib-grid{display:grid;gap:16px;grid-template-columns:repeat(4,1fr);}" +
  "@media (max-width:900px){.s4lib-grid{grid-template-columns:repeat(2,1fr);}}" +
  "@media (max-width:460px){.s4lib-grid{grid-template-columns:1fr;}}" +
  ".s4lib-tile{transition:box-shadow .2s ease,border-color .2s ease,transform .2s ease;}" +
  ".s4lib-tile:hover,.s4lib-tile:focus-visible{box-shadow:0 22px 50px rgba(0,0,0,.6),0 0 32px var(--s4-glow);border-color:var(--s4-accent);outline:none;}" +
  ".s4lib-tile:hover .s4lib-play,.s4lib-tile:focus-visible .s4lib-play{background:var(--s4-accent);color:#07080c;border-color:var(--s4-accent);}" +
  ".s4lib-cover{transition:transform .4s ease;}" +
  ".s4lib-hero{transition:box-shadow .2s ease,border-color .2s ease;}" +
  ".s4lib-hero:hover{box-shadow:0 26px 70px rgba(0,0,0,.6),0 0 40px var(--s4-glow);}" +
  ".s4lib-btn{transition:transform .16s ease,filter .16s ease,background .16s ease,border-color .16s ease;}" +
  ".s4lib-btn-primary:hover{filter:brightness(1.08);}" +
  ".s4lib-btn-ghost:hover{background:rgba(255,255,255,.13);border-color:rgba(255,255,255,.42);}" +
  "@media (prefers-reduced-motion: no-preference){" +
  ".s4lib-tile:hover,.s4lib-tile:focus-visible{transform:translateY(-6px) scale(1.02);}" +
  ".s4lib-tile:hover .s4lib-cover,.s4lib-hero:hover .s4lib-cover{transform:scale(1.05);}" +
  ".s4lib-btn-primary:hover,.s4lib-btn-ghost:hover{transform:translateY(-2px);}" +
  "}";
