export const STRINGS: Record<"en" | "ko" | "zh", S5Dict> = { en, ko, zh };

/**
 * Fill a dict template's {name} placeholders. Placeholders a language's
 * template omits are simply not rendered; unknown placeholders pass through
 * untouched (visible in QA rather than silently eaten).
 */
export function fill(tpl: string, vars: Record<string, string | number>): string {
  return tpl.replace(/\{(\w+)\}/g, (m, k: string) =>
    Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m,
  );
}
